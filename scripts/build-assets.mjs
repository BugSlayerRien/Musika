/* ============================================================
   MUSIKA — asset builder
   ------------------------------------------------------------
   Rasterises the SVG artwork in scripts/lib into real PNG files
   under public/aero, and writes a manifest the app reads.

   Everything here is drawn by us. Nothing is scraped, so the
   whole set ships with the project without a licence question.

   Run:  npm run assets
   ============================================================ */

import sharp from 'sharp';
import { mkdir, writeFile, readdir, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { SCENES, SCENE_SIZE } from './lib/svg-scenes.mjs';
import { DECALS } from './lib/svg-decals.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const AERO = join(ROOT, 'public', 'aero');
const BG = join(AERO, 'bg');
const PNG = join(AERO, 'png');

const kb = (n) => `${(n / 1024).toFixed(0)}kb`;

async function buildBackgrounds() {
  await mkdir(BG, { recursive: true });
  const out = {};
  for (const [name, draw] of Object.entries(SCENES)) {
    const svg = Buffer.from(draw());

    // Full-size scene.
    const full = join(BG, `${name}.png`);
    const info = await sharp(svg, { density: 96 })
      .resize(SCENE_SIZE.W, SCENE_SIZE.H)
      .png({ compressionLevel: 9, quality: 88, effort: 9 })
      .toFile(full);

    // A tiny version the app can show instantly while the full one loads.
    const tiny = join(BG, `${name}-thumb.png`);
    await sharp(svg, { density: 96 })
      .resize(64, 36)
      .png({ compressionLevel: 9 })
      .toFile(tiny);

    out[name] = { src: `/aero/bg/${name}.png`, thumb: `/aero/bg/${name}-thumb.png` };
    console.log(`bg  ${name.padEnd(10)} ${String(info.width)}x${info.height}  ${kb(info.size)}`);
  }
  return out;
}

async function buildDecals() {
  await mkdir(PNG, { recursive: true });
  const out = {};
  for (const [name, svg] of Object.entries(DECALS)) {
    const file = join(PNG, `${name}.png`);
    const info = await sharp(Buffer.from(svg), { density: 220 })
      .png({ compressionLevel: 9, effort: 9 })
      .toFile(file);
    out[name] = `/aero/png/${name}.png`;
    console.log(`png ${name.padEnd(16)} ${info.width}x${info.height}  ${kb(info.size)}`);
  }
  return out;
}

async function dirSize(dir) {
  let total = 0;
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    total += entry.isDirectory() ? await dirSize(p) : (await stat(p)).size;
  }
  return total;
}

async function main() {
  console.log('drawing scenes…\n');
  const backgrounds = await buildDecals().then(async (decals) => ({
    decals,
    backgrounds: await buildBackgrounds(),
  }));

  const manifest = {
    generated: new Date().toISOString(),
    note: 'Generated by npm run assets. Drawn from scripts/lib/*.mjs — do not hand-edit.',
    ...backgrounds,
  };

  await writeFile(
    join(AERO, 'manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8',
  );

  console.log(`\ntotal public/aero: ${kb(await dirSize(AERO))}`);
  console.log('manifest written to public/aero/manifest.json');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
